const defaultMinutes = {
  Beginner: 15,
  Intermediate: 25,
  Advanced: 40,
  Expert: 60,
};
const challenges = entries.map(
  ([
    id,
    slug,
    title,
    difficulty,
    skills,
    feature,
    application,
    scenario,
    objective,
    testData,
    expectedResult,
    hints,
    guide,
    relatedFixtures,
    starterCode,
  ]) => ({
    id,
    slug,
    title,
    difficulty,
    skills,
    technology: 'Playwright',
    feature,
    application,
    scenario,
    objective,
    preconditions: [
      'Use a fresh isolated Practice Lab browser context.',
      `Open the fixture identified by ${relatedFixtures.join(', ')}.`,
    ],
    testData,
    expectedResult,
    hints,
    relatedGuide: guides[guide],
    relatedFixtures,
    ...(starterCode ? { starterCode } : {}),
    solutionApproach: [hints[0], hints[1], hints[2]],
    estimatedMinutes: defaultMinutes[difficulty],
    version: '1.0.0',
  }),
);

export function renderChallenges() {
  return `${JSON.stringify({ catalogueVersion: '1.0.0', updatedAt: '2026-10-11', challenges }, null, 2)}\n`;
}

export async function writeChallenges(root = process.cwd()) {
  const directory = resolve(root, 'content/challenges');
  await mkdir(directory, { recursive: true });
  await writeFile(
    resolve(directory, 'challenges.json'),
    renderChallenges(),
    'utf8',
  );
  return challenges.length;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  console.log(`Generated ${await writeChallenges()} Practice Lab challenges.`);
}
